export function getTranslation(key: TranslationKey, lang: string = 'en'): string {
  const normalizedLang = lang?.toLowerCase() || 'en';
  const langPack = TRANSLATIONS[normalizedLang] || TRANSLATIONS['en'];
  if (langPack && langPack[key]) {
    return langPack[key]!;
  }
  // Fallback to English
  return TRANSLATIONS['en']?.[key] || key;
}
